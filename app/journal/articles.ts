export function getAdjacentArticles(slug: string): {
  prev: Article | null;
  next: Article | null;
} {
  const idx = ARTICLES.findIndex((a) => a.slug === slug);
  return {
    prev: idx > 0 ? ARTICLES[idx - 1] : null,
    next: idx < ARTICLES.length - 1 ? ARTICLES[idx + 1] : null,
  };
}
